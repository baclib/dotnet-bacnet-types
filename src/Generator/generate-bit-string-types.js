import { writeFileSync } from 'fs';
import fs from 'fs/promises';
import { EOL } from 'os';
import path from 'path';
import { fileURLToPath } from 'url';
import Handlebars from 'handlebars';
import { traverseDefinitions } from '@baclib/generic-bacnet-types/src/traverse.js';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const specialVariableLengths = new Map([
    ['bit-string-8', 8],
    ['bit-string-16', 16],
    ['bit-string-32', 32],
    ['bit-string-64', 64],
]);

const csharpKeywords = new Set([
    'abstract', 'as', 'base', 'bool', 'break', 'byte', 'case', 'catch', 'char', 'checked', 'class',
    'const', 'continue', 'decimal', 'default', 'delegate', 'do', 'double', 'else', 'enum', 'event',
    'explicit', 'extern', 'false', 'finally', 'fixed', 'float', 'for', 'foreach', 'goto', 'if',
    'implicit', 'in', 'int', 'interface', 'internal', 'is', 'lock', 'long', 'namespace', 'new',
    'null', 'object', 'operator', 'out', 'override', 'params', 'private', 'protected', 'public',
    'readonly', 'ref', 'return', 'sbyte', 'sealed', 'short', 'sizeof', 'stackalloc', 'static',
    'string', 'struct', 'switch', 'this', 'throw', 'true', 'try', 'typeof', 'uint', 'ulong',
    'unchecked', 'unsafe', 'ushort', 'using', 'virtual', 'void', 'volatile', 'while'
]);

class BitStringTypeGenerator {
    constructor(options = {}) {
        this.outputDirectory = options.outputDirectory
            ? path.resolve(options.outputDirectory)
            : (process.env.BITSTRING_OUTPUT_DIR
                ? path.resolve(__dirname, process.env.BITSTRING_OUTPUT_DIR)
                : path.join(__dirname, '..', '..', 'local-working-files', 'bitstrings'));
        this.cleanupMode = options.cleanupMode ?? 'all-cs';
        this.templatesDir = path.join(__dirname, 'templates');
        this.templateCache = new Map();
        this.partialsRegistered = false;
        this.fileObjects = [];
    }

    async start() {
        await fs.mkdir(this.outputDirectory, { recursive: true });
        await this.registerPartials();
    }

    endDefinition(context) {}

    startDefinition(context) {
        if (!this.isPrimitiveBitString(context)) {
            return;
        }

        const fileObject = this.createFileObject(context, []);
        this.fileObjects.push(fileObject);
    }

    startTraits(context) {
        context.userContext = [];
    }

    isSeries(context) {
        return context.traits && Object.hasOwn(context.traits, 'series') && context.traits.series !== false;
    }

    isPrimitiveBitString(context) {
        if (context.traits !== undefined) {
            return false;
        }

        return context.definition?.primitive === 8 || context.fullname === 'bit-string';
    }

    endTraits(context) {
        if (context.traits?.base !== 'bit-string') {
            return;
        }

        // SEQUENCE OF bit-string definitions represent collection wrappers and should not be emitted as bit-string structs.
        if (this.isSeries(context)) {
            return;
        }

        const bits = (context.userContext ?? [])
            .filter(item => Number.isInteger(item.position))
            .sort((left, right) => left.position - right.position);

        const fileObject = this.createFileObject(context, bits);
        this.fileObjects.push(fileObject);
    }

    startItem(context) {}

    endItem(context) {
        const parent = context.ancestors.at(-1);
        if (parent?.traits?.base !== 'bit-string') {
            return;
        }

        const position = this.toInteger(context.item?.position);
        const rawName = String(context.item?.name ?? 'Bit');
        parent.userContext.push({
            position,
            rawName,
            propertyName: this.toSafeIdentifier(this.toPascalCase(rawName)),
            description: this.toSentence(context.item?.description)
        });
    }

    async afterProcessing() {
        this.ensurePrimitiveBitStringFileObject();

        const existingFiles = await fs.readdir(this.outputDirectory);
        if (this.cleanupMode === 'all-cs') {
            for (const file of existingFiles) {
                if (file.endsWith('.cs')) {
                    await fs.unlink(path.join(this.outputDirectory, file));
                }
            }
        }
        else if (this.cleanupMode === 'generated-only') {
            for (const file of existingFiles) {
                if (!file.endsWith('.cs')) {
                    continue;
                }

                const filePath = path.join(this.outputDirectory, file);
                const content = await fs.readFile(filePath, 'utf-8');
                if (content.includes('// Generated by src/Generator/generate-bit-string-types.js')) {
                    await fs.unlink(filePath);
                }
            }
        }

        for (const fileObject of this.fileObjects) {
            const content = await this.render(fileObject);
            writeFileSync(path.join(this.outputDirectory, fileObject.fileName), content, 'utf-8');
        }

        console.log(`Generated ${this.fileObjects.length} bit-string types in ${this.outputDirectory}.`);
    }

    ensurePrimitiveBitStringFileObject() {
        const alreadyPresent = this.fileObjects.some(fileObject =>
            fileObject.fileName === 'BitString.cs' || fileObject.fullname === 'bit-string');

        if (alreadyPresent) {
            return;
        }

        this.fileObjects.push({
            fullname: 'bit-string',
            bacnetName: 'BitString',
            fileName: 'BitString.cs',
            typeName: 'BitString',
            classHierarchy: [],
            storageType: 'byte[]',
            minimum: 0,
            maximum: null,
            isVariable: true,
            countType: 'ushort',
            bits: []
        });
    }

    createFileObject(context, bits) {
        const hierarchy = this.getTypeHierarchy(context.fullname);
        const typeName = hierarchy.at(-1);
        const classHierarchy = hierarchy.slice(0, hierarchy.length - 1);
        const fileName = `${hierarchy.join('.')}.cs`;
        const isSpecialVariable = specialVariableLengths.has(context.fullname);

        const inferredFixedLength = bits.length > 0
            ? Math.max(...bits.map(item => item.position)) + 1
            : null;

        const lengthInfo = this.resolveLengthInfo(context.traits?.length, inferredFixedLength, isSpecialVariable, context.fullname);
        const storageType = this.resolveStorageType(lengthInfo.maximum ?? lengthInfo.minimum);

        const uniqueBits = this.ensureUniquePropertyNames(bits);

        return {
            fullname: context.fullname,
            bacnetName: context.thisAlias ?? context.thisName,
            fileName,
            typeName,
            classHierarchy,
            storageType,
            minimum: lengthInfo.minimum,
            maximum: lengthInfo.maximum,
            isVariable: lengthInfo.isVariable,
            countType: this.getCountType(lengthInfo.maximum),
            bits: uniqueBits
        };
    }

    getCountType(maximum) {
        if (!Number.isInteger(maximum)) {
            return 'ushort';
        }

        if (Number.isInteger(maximum) && maximum > 255) {
            return 'ushort';
        }
        return 'byte';
    }

    resolveLengthInfo(lengthTrait, inferredFixedLength, isSpecialVariable, fullname) {
        if (isSpecialVariable) {
            const max = specialVariableLengths.get(fullname);
            return { minimum: 0, maximum: max, isVariable: true };
        }

        if (Number.isInteger(lengthTrait)) {
            return { minimum: lengthTrait, maximum: lengthTrait, isVariable: false };
        }

        if (lengthTrait && typeof lengthTrait === 'object') {
            const minimum = this.toInteger(lengthTrait.minimum) ?? 0;
            const maximum = this.toInteger(lengthTrait.maximum);
            if (minimum === maximum && maximum !== null) {
                return { minimum, maximum, isVariable: false };
            }
            return { minimum, maximum, isVariable: true };
        }

        if (Number.isInteger(inferredFixedLength)) {
            return { minimum: inferredFixedLength, maximum: inferredFixedLength, isVariable: false };
        }

        return { minimum: 0, maximum: null, isVariable: true };
    }

    resolveStorageType(maxLength) {
        if (!Number.isInteger(maxLength)) {
            return 'byte[]';
        }

        if (maxLength <= 8) {
            return 'byte';
        }
        if (maxLength <= 16) {
            return 'ushort';
        }
        if (maxLength <= 32) {
            return 'uint';
        }
        if (maxLength <= 64) {
            return 'ulong';
        }
        return 'byte[]';
    }

    ensureUniquePropertyNames(bits) {
        const seen = new Map();
        const result = [];

        for (const bit of bits) {
            const key = bit.propertyName;
            const count = seen.get(key) ?? 0;
            seen.set(key, count + 1);
            result.push({
                ...bit,
                propertyName: count === 0 ? key : `${key}${count + 1}`
            });
        }

        return result;
    }

    async render(fileObject) {
        const content = await this.renderType(fileObject);
        const wrapped = this.wrapInHierarchy(fileObject.classHierarchy, content);
        return this.normalizeLineEndings(`// <auto-generated />
// Generated by src/Generator/generate-bit-string-types.js

namespace Baclib.Bacnet.Types.Application;

${wrapped}
`);
    }

    async renderType(fileObject) {
        const templatePath = path.join(this.templatesDir, 'bit-string-type.hbs');
        const template = await this.loadTemplate(templatePath);
        const model = this.toTemplateModel(fileObject);
        return template(model);
    }

    toTemplateModel(fileObject) {
        const constructorLines = (fileObject.isVariable
            ? this.renderVariableConstructor(fileObject)
            : this.renderFixedConstructor(fileObject));

        const indexerLines = this.renderIndexer(fileObject);
        const helperLines = this.renderHelpers(fileObject);

        return {
            ...fileObject,
            hasBits: fileObject.bits.length > 0,
            isArrayStorage: fileObject.storageType === 'byte[]',
            maxLengthLiteral: fileObject.maximum ?? 'int.MaxValue',
            constructorLines,
            indexerLines,
            helperLines
        };
    }

    async registerPartials() {
        if (this.partialsRegistered) {
            return;
        }

        const partials = [
            ['bitstring-length', 'bit-string-length.hbs'],
            ['bitstring-constructor', 'bit-string-constructor.hbs'],
            ['bitstring-bit-properties', 'bit-string-bit-properties.hbs'],
            ['bitstring-indexer', 'bit-string-indexer.hbs'],
            ['bitstring-helpers', 'bit-string-helpers.hbs']
        ];

        for (const [name, fileName] of partials) {
            const partialPath = path.join(this.templatesDir, fileName);
            const partialContent = await fs.readFile(partialPath, 'utf-8');
            Handlebars.registerPartial(name, partialContent);
        }

        this.partialsRegistered = true;
    }

    async loadTemplate(templatePath) {
        if (this.templateCache.has(templatePath)) {
            return this.templateCache.get(templatePath);
        }

        const templateContent = await fs.readFile(templatePath, 'utf-8');
        const compiledTemplate = Handlebars.compile(templateContent, { noEscape: true });
        this.templateCache.set(templatePath, compiledTemplate);
        return compiledTemplate;
    }

    renderVariableConstructor(fileObject) {
        if (fileObject.storageType === 'byte[]') {
            return [
                '    /// <summary>',
                `    /// Initializes a new instance of <see cref="${fileObject.typeName}"/> with a variable number of bits.`,
                '    /// </summary>',
                '    /// <param name="flags">Bit payload bytes in LSB-first bit order.</param>',
                `    /// <param name="count">Number of valid bits in <paramref name="flags"/>. Valid range is <see cref="MinLength"/> to <see cref="MaxLength"/>.</param>`,
                '    /// <exception cref="ArgumentNullException">Thrown when <paramref name="flags"/> is <see langword="null"/>.</exception>',
                '    /// <exception cref="ArgumentOutOfRangeException">Thrown when <paramref name="count"/> is out of range, or when <paramref name="flags"/> is shorter than required for <paramref name="count"/>.</exception>',
                `    public ${fileObject.typeName}(byte[] flags, ${fileObject.countType} count)`,
                '    {',
                `        ArgumentOutOfRangeException.ThrowIfLessThan((int)count, MinLength, nameof(count));`,
                '        if (MaxLength != int.MaxValue)',
                '        {',
                `            ArgumentOutOfRangeException.ThrowIfGreaterThan((int)count, MaxLength, nameof(count));`,
                '        }',
                '',
                '        int requiredBytes = GetRequiredByteCount((int)count);',
                '        ArgumentNullException.ThrowIfNull(flags, nameof(flags));',
                '        ArgumentOutOfRangeException.ThrowIfLessThan(flags.Length, requiredBytes, nameof(flags));',
                '',
                '        _count = count;',
                '        Flags = new byte[requiredBytes];',
                '        Array.Copy(flags, Flags, requiredBytes);',
                '    }'
            ];
        }

        return [
            '    /// <summary>',
            `    /// Initializes a new instance of <see cref="${fileObject.typeName}"/> with a variable number of bits.`,
            '    /// </summary>',
            `    /// <param name="flags">Underlying ${fileObject.storageType} bit container in LSB-first bit order.</param>`,
            `    /// <param name="count">Number of valid bits in <paramref name="flags"/>. Valid range is <see cref="MinLength"/> to <see cref="MaxLength"/>.</param>`,
            '    /// <exception cref="ArgumentOutOfRangeException">Thrown when <paramref name="count"/> is out of range.</exception>',
            `    public ${fileObject.typeName}(${fileObject.storageType} flags, ${fileObject.countType} count)`,
            '    {',
            `        ArgumentOutOfRangeException.ThrowIfLessThan((int)count, MinLength, nameof(count));`,
            '        if (MaxLength != int.MaxValue)',
            '        {',
            `            ArgumentOutOfRangeException.ThrowIfGreaterThan((int)count, MaxLength, nameof(count));`,
            '        }',
            '',
            '        _count = count;',
            `        Flags = MaskToCount(flags, (int)count);`,
            '    }'
        ];
    }

    renderFixedConstructor(fileObject) {
        if (fileObject.storageType === 'byte[]') {
            return [
                '    /// <summary>',
                `    /// Initializes a new instance of <see cref="${fileObject.typeName}"/> with a fixed bit length.`,
                '    /// </summary>',
                '    /// <param name="flags">Bit payload bytes in LSB-first bit order.</param>',
                '    /// <exception cref="ArgumentNullException">Thrown when <paramref name="flags"/> is <see langword="null"/>.</exception>',
                '    /// <exception cref="ArgumentOutOfRangeException">Thrown when <paramref name="flags"/> is shorter than the required byte count for <see cref="FixedLength"/>.</exception>',
                `    public ${fileObject.typeName}(byte[] flags)`,
                '    {',
                '        int requiredBytes = GetRequiredByteCount(FixedLength);',
                '        ArgumentNullException.ThrowIfNull(flags, nameof(flags));',
                '        ArgumentOutOfRangeException.ThrowIfLessThan(flags.Length, requiredBytes, nameof(flags));',
                '',
                '        Flags = new byte[requiredBytes];',
                '        Array.Copy(flags, Flags, requiredBytes);',
                '    }'
            ];
        }

        return [
            '    /// <summary>',
            `    /// Initializes a new instance of <see cref="${fileObject.typeName}"/> with a fixed bit length.`,
            '    /// </summary>',
            `    /// <param name="flags">Underlying ${fileObject.storageType} bit container in LSB-first bit order.</param>`,
            `    public ${fileObject.typeName}(${fileObject.storageType} flags)`,
            '    {',
            '        Flags = MaskToCount(flags, FixedLength);',
            '    }'
        ];
    }

    renderIndexer(fileObject) {
        if (fileObject.storageType === 'byte[]') {
            return [
                '    /// <summary>',
                '    /// Gets whether the bit at the specified zero-based index is set.',
                '    /// </summary>',
                '    /// <param name="index">Zero-based bit index.</param>',
                '    /// <returns><see langword="true"/> when the bit is set; otherwise <see langword="false"/>.</returns>',
                '    /// <exception cref="ArgumentOutOfRangeException">Thrown when <paramref name="index"/> is outside the range <c>0..Count-1</c>.</exception>',
                '    public bool this[int index]',
                '    {',
                '        get',
                '        {',
                '            ArgumentOutOfRangeException.ThrowIfNegative(index, nameof(index));',
                '            ArgumentOutOfRangeException.ThrowIfGreaterThanOrEqual(index, Length, nameof(index));',
                '',
                '            int byteIndex = index / 8;',
                '            int bitOffset = index % 8;',
                '            return (Flags[byteIndex] & (1 << bitOffset)) != 0;',
                '        }',
                '    }'
            ];
        }

        const bitTest = this.getScalarBitTestExpression(fileObject.storageType, 'Flags', 'index');
        return [
            '    /// <summary>',
            '    /// Gets whether the bit at the specified zero-based index is set.',
            '    /// </summary>',
            '    /// <param name="index">Zero-based bit index.</param>',
            '    /// <returns><see langword="true"/> when the bit is set; otherwise <see langword="false"/>.</returns>',
            '    /// <exception cref="ArgumentOutOfRangeException">Thrown when <paramref name="index"/> is outside the range <c>0..Count-1</c>.</exception>',
            '    public bool this[int index]',
            '    {',
            '        get',
            '        {',
            '            ArgumentOutOfRangeException.ThrowIfNegative(index, nameof(index));',
            '            ArgumentOutOfRangeException.ThrowIfGreaterThanOrEqual(index, Length, nameof(index));',
            `            return ${bitTest};`,
            '        }',
            '    }'
        ];
    }

    renderHelpers(fileObject) {
        if (fileObject.storageType === 'byte[]') {
            return [
                '    /// <summary>',
                '    /// Calculates the minimum number of bytes required to store the specified number of bits.',
                '    /// </summary>',
                '    /// <param name="bitCount">Bit count to convert to a byte count.</param>',
                '    /// <returns>Required byte count.</returns>',
                '    private static int GetRequiredByteCount(int bitCount)',
                '    {',
                '        if (bitCount <= 0)',
                '        {',
                '            return 0;',
                '        }',
                '',
                '        return (bitCount + 7) / 8;',
                '    }'
            ];
        }

        const helper = this.getScalarMaskHelper(fileObject.storageType);
        return [
            '    /// <summary>',
            '    /// Clears all bits above the provided bit count and returns the normalized value.',
            '    /// </summary>',
            '    /// <param name="flags">Input bit container.</param>',
            '    /// <param name="count">Number of valid low-order bits to preserve.</param>',
            '    /// <returns>Masked flag value containing only the valid bits.</returns>',
            '    /// <exception cref="ArgumentOutOfRangeException">Thrown when <paramref name="count"/> is outside the supported bit range for this storage type.</exception>',
            `    private static ${fileObject.storageType} MaskToCount(${fileObject.storageType} flags, int count)`,
            '    {',
            '        ArgumentOutOfRangeException.ThrowIfNegative(count, nameof(count));',
            `        ArgumentOutOfRangeException.ThrowIfGreaterThan(count, ${helper.maxBits}, nameof(count));`,
            '',
            `        ${helper.maskExpression}`,
            '    }'
        ];
    }

    getScalarMaskHelper(storageType) {
        switch (storageType) {
            case 'byte':
                return {
                    maxBits: 8,
                    maskExpression: 'if (count == 0) return 0;\n        if (count >= 8) return flags;\n        byte mask = (byte)((1 << count) - 1);\n        return (byte)(flags & mask);'
                };
            case 'ushort':
                return {
                    maxBits: 16,
                    maskExpression: 'if (count == 0) return 0;\n        if (count >= 16) return flags;\n        ushort mask = (ushort)((1u << count) - 1u);\n        return (ushort)(flags & mask);'
                };
            case 'uint':
                return {
                    maxBits: 32,
                    maskExpression: 'if (count == 0) return 0;\n        if (count >= 32) return flags;\n        uint mask = (1u << count) - 1u;\n        return flags & mask;'
                };
            case 'ulong':
                return {
                    maxBits: 64,
                    maskExpression: 'if (count == 0) return 0;\n        if (count >= 64) return flags;\n        ulong mask = (1ul << count) - 1ul;\n        return flags & mask;'
                };
            default:
                throw new Error(`Unsupported scalar storage type: ${storageType}`);
        }
    }

    getScalarBitTestExpression(storageType, flagsExpr, indexExpr) {
        switch (storageType) {
            case 'byte':
            case 'ushort':
                return `(${flagsExpr} & (1 << ${indexExpr})) != 0`;
            case 'uint':
                return `(${flagsExpr} & (1u << ${indexExpr})) != 0`;
            case 'ulong':
                return `(${flagsExpr} & (1ul << ${indexExpr})) != 0`;
            default:
                throw new Error(`Unsupported scalar storage type: ${storageType}`);
        }
    }

    wrapInHierarchy(classHierarchy, content) {
        if (!classHierarchy.length) {
            return content;
        }

        let start = '';
        let end = '';
        for (let i = 0; i < classHierarchy.length; i++) {
            const indentation = ' '.repeat(i * 4);
            start += `${indentation}public partial record class ${classHierarchy[i]}\n${indentation}{\n`;
            end = `${indentation}}\n` + end;
        }

        const contentIndent = ' '.repeat(classHierarchy.length * 4);
        const indented = content
            .split('\n')
            .map(line => `${contentIndent}${line}`)
            .join('\n');

        return `${start}${indented}\n${end}`;
    }

    getTypeHierarchy(fullname) {
        return fullname
            .split('.')
            .map((part, index) => (index ? 'T' : '') + this.toPascalCase(part));
    }

    toInteger(value) {
        if (typeof value === 'number' && Number.isInteger(value)) {
            return value;
        }
        if (typeof value === 'string' && /^-?\d+$/.test(value.trim())) {
            return Number.parseInt(value.trim(), 10);
        }
        return null;
    }

    toSentence(value) {
        const text = String(value ?? '').trim();
        if (!text) {
            return 'Named bit.';
        }
        return text
            .replace(/\s+/g, ' ')
            .replace(/[\r\n]+/g, ' ');
    }

    toSafeIdentifier(input) {
        let value = input.replace(/[^A-Za-z0-9_]/g, '');
        if (!value) {
            value = 'Bit';
        }
        if (/^\d/.test(value)) {
            value = `N${value}`;
        }
        if (csharpKeywords.has(value.toLowerCase())) {
            value = `${value}_`;
        }
        return value;
    }

    toPascalCase(value) {
        return String(value)
            .split(/[^A-Za-z0-9]+/g)
            .filter(Boolean)
            .map(part => part.charAt(0).toUpperCase() + part.slice(1))
            .join('');
    }

    normalizeLineEndings(content) {
        return content.replace(/\r\n|\n|\r/g, EOL);
    }
}

export async function generateBitStringTypes(options = {}) {
    const generator = new BitStringTypeGenerator(options);
    await traverseDefinitions(generator);
}

if (process.argv[1] && path.resolve(process.argv[1]) === __filename) {
    await generateBitStringTypes();
}
